void inputHidOpened(const uint8_t *const *maps, const uint16_t *mapLengths, int numMaps)
{
    int n = 0;
    for (int m = 0; m < numMaps; m++)
    {
        n = hidParseReportMap(m, maps[m], mapLengths[m], hidFields, n, MAX_HID_FIELDS);
    }
    hasRightStickZ = false;
    for (int i = 0; i < n; i++)
    {
        const hidField_t *f = &hidFields[i];
        if (f->usagePage == HID_PAGE_GENERIC_DESKTOP && (f->flags & HID_FLAG_VARIABLE) && !(f->flags & HID_FLAG_RELATIVE))
        {
            for (int j = 0; j < f->count; j++)
            {
                if (hidGetVariableUsage(f, j) == 0x32 || hidGetVariableUsage(f, j) == 0x35)
                {
                    hasRightStickZ = true;
                }
            }
        }
    }
    numHidFields = n;
    touchHideOverlay();
    printf("HID: %d input fields, right stick on %s\n", n, hasRightStickZ ? "Z/Rz" : "Rx/Ry");
}

bool inputHidHasFields(void)
{
    return numHidFields > 0;
}

static int8_t normalizeAxis(const hidField_t *f, int32_t v)
{
    int32_t range = f->logicalMax - f->logicalMin;
    if (range <= 0)
        return 0;
    int32_t n = (int32_t) (((int64_t) (v - f->logicalMin) * 255) / range) - 128;
    if (n > -STICK_DEADZONE && n < STICK_DEADZONE)
        return 0;
    return n < -128 ? -128 : (n > 127 ? 127 : n);
}

static uint8_t normalizeTrigger(const hidField_t *f, int32_t v)
{
    int32_t range = f->logicalMax - f->logicalMin;
    if (range <= 0)
        return 0;
    int32_t n = (int32_t) (((int64_t) (v - f->logicalMin) * 255) / range);
    return n < 0 ? 0 : (n > 255 ? 255 : n);
}

static void setKeyboardUsage(uint8_t *keys, uint32_t usage)
{
    if (usage < 256)
    {
        keys[usage >> 3] |= 1 << (usage & 7);
    }
}

void inputHidReport(uint8_t mapIndex, uint8_t reportId, const uint8_t *data, int len)
{
    uint8_t newKeys[32] = { 0 };
    bool hasKeyboard = false, hasButtons = false;
    uint32_t buttons = 0;
    uint32_t dpad = 0;
    bool hasDpad = false;
    uint32_t mouseButtons = 0;
    bool isMouse = false;
    for (int i = 0; i < numHidFields; i++)
    {
        const hidField_t *f = &hidFields[i];
        if (f->mapIndex != mapIndex || f->reportId != reportId)
            continue;
        bool variable = f->flags & HID_FLAG_VARIABLE;
        for (int j = 0; j < f->count; j++)
        {
            int32_t v = hidGetFieldValue(f, j, data, len);
            uint32_t usage;
            if (variable)
            {
                usage = hidGetVariableUsage(f, j);
            }
            else
            {
                // array: the value is an index in the usage range
                if (v < f->logicalMin || v > f->logicalMax)
                    continue;
                usage = f->usageMin + (v - f->logicalMin);
                if (!usage)
                    continue;
            }
            switch (f->usagePage)
            {
                case HID_PAGE_KEYBOARD:
                    hasKeyboard = true;
                    if (!variable || v)
                    {
                        setKeyboardUsage(newKeys, usage);
                    }
                    break;
                case HID_PAGE_BUTTON:
                    if (f->flags & HID_FLAG_RELATIVE)
                        break;
                    if (!variable || v)
                    {
                        if (usage >= 1 && usage <= 32)
                        {
                            buttons |= 1u << (usage - 1);
                        }
                    }
                    hasButtons = true;
                    break;
                case HID_PAGE_GENERIC_DESKTOP:
                    if (f->flags & HID_FLAG_RELATIVE)
                    {
                        // mouse
                        isMouse = true;
                        portENTER_CRITICAL(&inputMux);
                        if (usage == 0x30)
                            mouseDX += v;
                        else if (usage == 0x31)
                            mouseDY += v;
                        portEXIT_CRITICAL(&inputMux);
                        if (usage == 0x38 && v)
                        {
                            inputPushKey(v > 0 ? K_MWHEELUP : K_MWHEELDOWN, true);
                            inputPushKey(v > 0 ? K_MWHEELUP : K_MWHEELDOWN, false);
                        }
                        break;
                    }
                    switch (usage)
                    {
                        case 0x30:
                            stickLX = normalizeAxis(f, v);
                            break;
                        case 0x31:
                            stickLY = normalizeAxis(f, v);
                            break;
                        case 0x32:
                            stickRX = normalizeAxis(f, v);
                            break;
                        case 0x35:
                            stickRY = normalizeAxis(f, v);
                            break;
                        case 0x33:
                            if (hasRightStickZ)
                                triggerL = normalizeTrigger(f, v);
                            else
                                stickRX = normalizeAxis(f, v);
                            break;
                        case 0x34:
                            if (hasRightStickZ)
                                triggerR = normalizeTrigger(f, v);
                            else
                                stickRY = normalizeAxis(f, v);
                            break;
                        case 0x39:  // hat switch
                        {
                            static const uint8_t hatToDpad[8] =
                            {
                                1 << (GP_UP - GP_UP), (1 << (GP_UP - GP_UP)) | (1 << (GP_RIGHT - GP_UP)), 1 << (GP_RIGHT - GP_UP),
                                (1 << (GP_DOWN - GP_UP)) | (1 << (GP_RIGHT - GP_UP)), 1 << (GP_DOWN - GP_UP),
                                (1 << (GP_DOWN - GP_UP)) | (1 << (GP_LEFT - GP_UP)), 1 << (GP_LEFT - GP_UP),
                                (1 << (GP_UP - GP_UP)) | (1 << (GP_LEFT - GP_UP)),
                            };
                            hasDpad = true;
                            int32_t d = v - f->logicalMin;
                            if (v >= f->logicalMin && v <= f->logicalMax && d < 8)
                            {
                                dpad |= hatToDpad[d];
                            }
                            break;
                        }
                        case 0x90:  // D-pad as buttons
                        case 0x91:
                        case 0x92:
                        case 0x93:
                        {
                            static const uint8_t dpadBit[4] = { GP_UP - GP_UP, GP_DOWN - GP_UP, GP_RIGHT - GP_UP, GP_LEFT - GP_UP };
                            hasDpad = true;
                            if (v)
                                dpad |= 1 << dpadBit[usage - 0x90];
                            break;
                        }
                        default:
                            break;
                    }
                    break;
                case HID_PAGE_SIMULATION:
                    if (usage == 0xC5)          // brake
                        triggerL = normalizeTrigger(f, v);
                    else if (usage == 0xC4)     // accelerator
                        triggerR = normalizeTrigger(f, v);
                    break;
                case HID_PAGE_CONSUMER:
                    // AC Home / AC Back, used as menu buttons by some gamepads
                    if (variable && (usage == 0x223 || usage == 0x224))
                    {
                        inputPushKey(K_ESCAPE, v != 0);
                    }
                    else if (!variable && (usage == 0x223 || usage == 0x224))
                    {
                        inputPushKey(K_ESCAPE, true);
                        inputPushKey(K_ESCAPE, false);
                    }
                    break;
                default:
                    break;
            }
        }
    }
    if (isMouse && hasButtons)
    {
        // mouse buttons: send directly as MOUSE1..3
        mouseButtons = buttons;
        static uint32_t oldMouseButtons;
        uint32_t changed = mouseButtons ^ oldMouseButtons;
        for (int b = 0; b < 3; b++)
        {
            if (changed & (1 << b))
            {
                inputPushKey(K_MOUSE1 + b, (mouseButtons >> b) & 1);
            }
        }
        oldMouseButtons = mouseButtons;
        hasButtons = false;
    }
    if (hasKeyboard)
    {
        // modifiers are usages 0xE0-0xE7
        for (int m = 0; m < 8; m++)
        {
            int oldDown = (hidKeysDown[0xE0 >> 3] >> m) & 1;
            int newDown = (newKeys[0xE0 >> 3] >> m) & 1;
            if (oldDown != newDown)
            {
                inputPushKey(hidModifierMap[m], newDown);
            }
        }
        for (int u = 0; u < (int) sizeof(hidKeyboardMap); u++)
        {
            int oldDown = (hidKeysDown[u >> 3] >> (u & 7)) & 1;
            int newDown = (newKeys[u >> 3] >> (u & 7)) & 1;
            if (oldDown != newDown)
            {
                inputPushKey(hidKeyboardMap[u], newDown);
            }
        }
        memcpy(hidKeysDown, newKeys, sizeof(hidKeysDown));
    }
    if (hasButtons || hasDpad)
    {
        uint32_t gp = hidGamepadButtons;
        if (hasButtons)
        {
            gp &= ((1u << GP_UP) | (1u << GP_DOWN) | (1u << GP_LEFT) | (1u << GP_RIGHT));
            for (int b = 0; b < 16; b++)
            {
                if ((buttons & (1u << b)) && hidButtonMap[b] >= 0)
                {
                    gp |= 1u << hidButtonMap[b];
                }
            }
        }
        if (hasDpad)
        {
            gp &= ~((1u << GP_UP) | (1u << GP_DOWN) | (1u << GP_LEFT) | (1u << GP_RIGHT));
            gp |= dpad << GP_UP;
        }
        hidGamepadButtons = gp;
    }
}

void inputHidClosed(void)
{
    // release everything
    for (int u = 0; u < 256; u++)
    {
        if (hidKeysDown[u >> 3] & (1 << (u & 7)))
        {
            if (u >= 0xE0 && u <= 0xE7)
                inputPushKey(hidModifierMap[u - 0xE0], false);
            else if (u < (int) sizeof(hidKeyboardMap))
                inputPushKey(hidKeyboardMap[u], false);
        }
    }
    memset(hidKeysDown, 0, sizeof(hidKeysDown));
    numHidFields = 0;
    hidGamepadButtons = 0;
    stickLX = stickLY = stickRX = stickRY = 0;
    triggerL = triggerR = 0;
}

