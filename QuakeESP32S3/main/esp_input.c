#define TRIGGER_DIGITAL_ON      96      // out of 255
#define TRIGGER_DIGITAL_OFF     64
#define MOUSE_SCALE             0.5f
#define TOUCH_YAW_PER_PIXEL     0.5f    // degrees per pixel at the default sensitivity (3)
#define TOUCH_PITCH_PER_PIXEL   0.4f

