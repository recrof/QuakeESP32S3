// ---------------------------------------------------------------------------
static uint32_t getVirtualGamepadButtons(bool inMenu)
{
    uint32_t gp = hidGamepadButtons | touchGetButtons();
    for (int i = 0; i < GP_NUM_BUTTONS; i++)
    {
        if (gpioButtons[i] >= 0 && !gpio_get_level(gpioButtons[i]))
        {
            gp |= 1u << i;
        }
    }
    if (boardWakeButtonPressed())
    {
        gp |= 1u << GP_A;       // jump in game, select in menus
    }
    // analog triggers as buttons (with hysteresis)
    static bool lt, rt;
    lt = triggerL > (lt ? TRIGGER_DIGITAL_OFF : TRIGGER_DIGITAL_ON);
    rt = triggerR > (rt ? TRIGGER_DIGITAL_OFF : TRIGGER_DIGITAL_ON);
    if (lt)
        gp |= 1u << GP_LT;
    if (rt)
        gp |= 1u << GP_RT;
    // in menus, the left stick works as arrows
    if (inMenu)
    {
        static uint32_t stickDirs;
        int x = stickLX, y = stickLY;
        uint32_t d = 0;
        d |= (y < -((stickDirs & (1 << GP_UP)) ? STICK_DIGITAL_OFF : STICK_DIGITAL_ON)) << GP_UP;
        d |= (y > ((stickDirs & (1 << GP_DOWN)) ? STICK_DIGITAL_OFF : STICK_DIGITAL_ON)) << GP_DOWN;
        d |= (x < -((stickDirs & (1 << GP_LEFT)) ? STICK_DIGITAL_OFF : STICK_DIGITAL_ON)) << GP_LEFT;
        d |= (x > ((stickDirs & (1 << GP_RIGHT)) ? STICK_DIGITAL_OFF : STICK_DIGITAL_ON)) << GP_RIGHT;
        stickDirs = d;
        gp |= d;
    }
    return gp;
}

void Sys_SendKeyEvents(void)
{
    keyEvent_t e;
    while (keyQueue && xQueueReceive(keyQueue, &e, 0) == pdTRUE)
    {
        Key_Event(e.key, e.down);
    }
    bool inMenu = key_dest != key_game;
    uint32_t gp = getVirtualGamepadButtons(inMenu);
    uint32_t changed = gp ^ oldGamepadButtons;
    for (int i = 0; i < GP_NUM_BUTTONS; i++)
    {
        if (!(changed & (1u << i)))
            continue;
        if (gp & (1u << i))
        {
            sentKey[i] = inMenu ? gpMenuKeys[i] : gpGameKeys[i];
            if (sentKey[i])
                Key_Event(sentKey[i], true);
        }
        else if (sentKey[i])
        {
            Key_Event(sentKey[i], false);
            sentKey[i] = 0;
        }
    }
    oldGamepadButtons = gp;
}

