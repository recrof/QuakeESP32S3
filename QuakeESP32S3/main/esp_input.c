void IN_Move(usercmd_t *cmd)
{
    if (key_dest != key_game)
    {
        return;
    }
    float mx, my;
    portENTER_CRITICAL(&inputMux);
    mx = mouseDX;
    my = mouseDY;
    mouseDX = mouseDY = 0;
    portEXIT_CRITICAL(&inputMux);
    float tsx, tsy, tdx, tdy;
    touchGetStick(&tsx, &tsy);
    touchTakeLook(&tdx, &tdy);
    float bdx, bdy;
    boardTakeLook(&bdx, &bdy);
    tdx += bdx;
    tdy += bdy;
    float lx = (stickLX + tsx) * sensitivity;
    float ly = (stickLY + tsy) * sensitivity;
    float rx = stickRX * sensitivity + mx * sensitivity * MOUSE_SCALE;
    float ry = stickRY * sensitivity + my * sensitivity * MOUSE_SCALE;
    _g->cl.viewangles[YAW] -= m_yaw * rx + tdx * TOUCH_YAW_PER_PIXEL * sensitivity / 3;
    _g->cl.viewangles[PITCH] += tdy * TOUCH_PITCH_PER_PIXEL * sensitivity / 3;
    if (ry || tdy)
    {
        V_StopPitchDrift();
        _g->cl.viewangles[PITCH] += m_pitch * ry;
        if (_g->cl.viewangles[PITCH] > 80)
            _g->cl.viewangles[PITCH] = 80;
        if (_g->cl.viewangles[PITCH] < -70)
            _g->cl.viewangles[PITCH] = -70;
    }
    cmd->forwardmove -= m_forward * ly;
    cmd->sidemove += m_side * lx;
}
